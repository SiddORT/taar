import { createRequire } from "node:module";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const require = createRequire(path.join(root, "artifacts/api-server/package.json"));
const sharp = require("sharp");
const source = path.join(root, "attached_assets/taar_logo_1793080544664.png");
const frontend = path.join(root, "artifacts/zari-erp");
const backend = path.join(root, "artifacts/api-server");
const tagline = "— YOUR DESIGN BUSINESS, CONNECTED";

for (const dir of ["src/assets", "public/brand"]) {
  await mkdir(path.join(frontend, dir), { recursive: true });
}
await mkdir(path.join(backend, "src/assets"), { recursive: true });

const wordmark = await sharp(source).resize({ width: 820 }).png().toBuffer();
const caption = Buffer.from(`<svg width="1200" height="380" xmlns="http://www.w3.org/2000/svg"><text x="64" y="315" font-family="DejaVu Sans,Arial,sans-serif" font-size="36" font-weight="600" letter-spacing="5" fill="#967322">${tagline}</text></svg>`);
const lockup = await sharp({
  create: { width: 1200, height: 380, channels: 4, background: "#ffffff" },
}).composite([
  { input: wordmark, left: 64, top: 36 },
  { input: caption, left: 0, top: 0 },
]).png().toBuffer();

await writeFile(path.join(frontend, "src/assets/taar-lockup.png"), lockup);
await writeFile(path.join(frontend, "public/brand/taar-lockup.png"), lockup);
const embeddedAsset = `// Generated by scripts/generate-taar-brand-assets.mjs.\nexport const TAAR_LOGO_DATA_URL = ${JSON.stringify(`data:image/png;base64,${lockup.toString("base64")}`)};\nexport const TAAR_LOGO_RATIO = 1200 / 380;\nexport const TAAR_TAGLINE = ${JSON.stringify(tagline)};\n`;
await writeFile(path.join(frontend, "src/assets/taarBrandData.ts"), embeddedAsset);
await writeFile(path.join(backend, "src/assets/taarBrandData.ts"), embeddedAsset);

// A compact crop of the supplied T remains legible at browser-tab sizes.
const initial = await sharp(source).extract({ left: 0, top: 0, width: 176, height: 215 })
  .resize(132, 160, { fit: "inside" }).png().toBuffer();
const icon = await sharp({ create: { width: 192, height: 192, channels: 4, background: "#ffffff" } })
  .composite([{ input: initial, gravity: "centre" }]).png().toBuffer();
await writeFile(path.join(frontend, "public/brand/taar-favicon.png"), icon);
await writeFile(path.join(frontend, "src/assets/taar-initial.png"), icon);
const socialLogo = await sharp(lockup).resize({ width: 1050 }).png().toBuffer();
await sharp({ create: { width: 1200, height: 630, channels: 4, background: "#ffffff" } })
  .composite([{ input: socialLogo, gravity: "centre" }]).png()
  .toFile(path.join(frontend, "public/brand/taar-social.png"));
console.info("Generated TAAR lockup, embedded PDF asset, favicon, and share image.");
